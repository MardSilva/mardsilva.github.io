const textElements = [...document.querySelectorAll('[data-i18n]')];
const htmlElements = [...document.querySelectorAll('[data-i18n-html]')];
const ariaElements = [...document.querySelectorAll('[data-i18n-aria]')];
const altElements = [...document.querySelectorAll('[data-i18n-alt]')];
const contentElements = [...document.querySelectorAll('[data-i18n-content]')];
const hrefElements = [...document.querySelectorAll('[data-i18n-href]')];
const languageButtons = [...document.querySelectorAll('[data-language]')];
const languageGroup = document.querySelector('.language-switcher');
const menuToggle = document.querySelector('.menu-toggle');
const mainNav = document.querySelector('.main-nav');

textElements.forEach(element => {
  element.dataset.defaultText = element.textContent;
});
htmlElements.forEach(element => {
  element.dataset.defaultHtml = element.innerHTML;
});
ariaElements.forEach(element => {
  element.dataset.defaultAria = element.getAttribute('aria-label') || '';
});
altElements.forEach(element => {
  element.dataset.defaultAlt = element.getAttribute('alt') || '';
});
contentElements.forEach(element => {
  element.dataset.defaultContent = element.getAttribute('content') || '';
});
hrefElements.forEach(element => {
  element.dataset.defaultHref = element.getAttribute('href') || '';
});

let currentLanguage = 'pt-PT';

function updateMenuLabel() {
  if (!menuToggle) return;
  const isOpen = menuToggle.getAttribute('aria-expanded') === 'true';
  menuToggle.setAttribute('aria-label', currentLanguage === 'en'
    ? (isOpen ? portfolioEnglish['menu.close'] : portfolioEnglish['menu.open'])
    : (isOpen ? 'Fechar menu' : 'Abrir menu'));
}

function setLanguage(language, persist = true) {
  currentLanguage = language === 'en' ? 'en' : 'pt-PT';
  const isEnglish = currentLanguage === 'en';
  document.documentElement.lang = currentLanguage;

  textElements.forEach(element => {
    element.textContent = isEnglish
      ? (portfolioEnglish[element.dataset.i18n] ?? element.dataset.defaultText)
      : element.dataset.defaultText;
  });
  htmlElements.forEach(element => {
    element.innerHTML = isEnglish
      ? (portfolioEnglish[element.dataset.i18nHtml] ?? element.dataset.defaultHtml)
      : element.dataset.defaultHtml;
  });
  ariaElements.forEach(element => {
    element.setAttribute('aria-label', isEnglish
      ? (portfolioEnglish[element.dataset.i18nAria] ?? element.dataset.defaultAria)
      : element.dataset.defaultAria);
  });
  altElements.forEach(element => {
    element.setAttribute('alt', isEnglish
      ? (portfolioEnglish[element.dataset.i18nAlt] ?? element.dataset.defaultAlt)
      : element.dataset.defaultAlt);
  });
  contentElements.forEach(element => {
    element.setAttribute('content', isEnglish
      ? (portfolioEnglish[element.dataset.i18nContent] ?? element.dataset.defaultContent)
      : element.dataset.defaultContent);
  });
  hrefElements.forEach(element => {
    element.setAttribute('href', isEnglish
      ? (portfolioEnglish[element.dataset.i18nHref] ?? element.dataset.defaultHref)
      : element.dataset.defaultHref);
  });

  languageButtons.forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === currentLanguage));
  });
  if (languageGroup) {
    languageGroup.setAttribute('aria-label', isEnglish ? 'Language' : 'Idioma');
  }
  updateMenuLabel();

  if (persist) {
    try {
      localStorage.setItem('mardsilva-portfolio-language', currentLanguage);
    } catch (_) {}
  }
}

languageButtons.forEach(button => {
  button.addEventListener('click', () => setLanguage(button.dataset.language));
});

if (menuToggle && mainNav) {
  menuToggle.addEventListener('click', () => {
    const isOpen = menuToggle.getAttribute('aria-expanded') === 'true';
    menuToggle.setAttribute('aria-expanded', String(!isOpen));
    mainNav.classList.toggle('is-open', !isOpen);
    updateMenuLabel();
  });

  mainNav.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => {
      menuToggle.setAttribute('aria-expanded', 'false');
      mainNav.classList.remove('is-open');
      updateMenuLabel();
    });
  });
}

let savedLanguage = null;
try {
  savedLanguage = localStorage.getItem('mardsilva-portfolio-language');
} catch (_) {}

const browserLanguage = (navigator.language || '').toLowerCase();
const initialLanguage = savedLanguage === 'en' || savedLanguage === 'pt-PT'
  ? savedLanguage
  : (browserLanguage.startsWith('en') ? 'en' : 'pt-PT');

setLanguage(initialLanguage, false);
document.getElementById('year').textContent = new Date().getFullYear();
